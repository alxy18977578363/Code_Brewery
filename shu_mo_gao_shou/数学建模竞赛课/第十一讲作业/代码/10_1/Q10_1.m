% 数据标准化（Z-score标准化）
data_normalized = zscore(data);

% 计算欧氏距离
distances = pdist(data_normalized);

% 层次聚类（使用ward方法）
link = linkage(distances, 'ward');

% 绘制树状图
figure;
dendrogram(link, 'Labels', province, 'Orientation', 'right');
title('中国省(自治区、直辖市)城市规模结构聚类树状图');
xlabel('距离');
set(gca, 'FontSize', 8);

% 计算轮廓系数评估不同聚类数
eva = evalclusters(data_normalized, 'linkage', 'silhouette', 'KList', 2:6);

% 显示评估结果
disp('轮廓系数评估结果:');
disp(eva);

% 绘制轮廓系数图
figure;
plot(eva);
title('轮廓系数评估最优聚类数');
xlabel('聚类数量');
ylabel('轮廓值');

% 自动选择最优聚类数
optimal_k = eva.OptimalK;
fprintf('\n根据轮廓系数，最优聚类数为: %d\n', optimal_k);

% 使用最优聚类数进行聚类
clusters = cluster(link, 'maxclust', optimal_k);

% 显示聚类结果
for k = 1:max(clusters)
    fprintf('第%d类:\n', k);
    disp(province(clusters == k)');
end

% 可视化聚类结果（前两个主成分）
