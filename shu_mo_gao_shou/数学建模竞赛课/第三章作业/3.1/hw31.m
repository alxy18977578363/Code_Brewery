% 定义不等式约束
A = [-1, 0, 0; % x1 >= 40
     -1, -1, 0; % x1 + x2 >= 100
     -1, -1, -1; % x1 + x2 + x3 >= 180
    ];
b = [-40; -100; -180];

% 定义变量的下界和上界
lb = [40; 0; 0]; % x1 >= 40, x2 >= 0, x3 >= 0
ub = [100; 100; 100]; % x1 <= 100, x2 <= 100, x3 <= 100

% 调用ga来解题
[x,fval] = ga(@fun1,3,A,b,[],[],lb,ub,[], [1, 2, 3]);

% 输出结果
disp('最优解为:');
disp(x);
disp('最优值为:');
disp(fval);