def para(text="", *, size=11, bold=False, align=None, italic=False, color=None, indent=True):
    p = doc.add_paragraph()
    if align:
        p.alignment = align
    if indent and align is None:
        p.paragraph_format.first_line_indent = Pt(22)
    r = p.add_run(text)
    r.bold = bold; r.italic = italic; r.font.size = Pt(size)
    if color:
        r.font.color.rgb = color
    _cn(r)
    return p


def term(label, text):
    """术语解释段：加粗术语 + 解释。"""
    p = doc.add_paragraph()
    p.paragraph_format.first_line_indent = Pt(22)
    r = p.add_run(label + "：")
    r.bold = True; r.font.size = Pt(11); r.font.color.rgb = BLUE; _cn(r)
    r2 = p.add_run(text); r2.font.size = Pt(11); _cn(r2)
    return p


def bullets(items):
    for it in items:
        p = doc.add_paragraph(style="List Bullet")
        if isinstance(it, tuple):
            r = p.add_run(it[0] + "："); r.bold = True; r.font.size = Pt(11); _cn(r)
            r2 = p.add_run(it[1]); r2.font.size = Pt(11); _cn(r2)
        else:
            r = p.add_run(it); r.font.size = Pt(11); _cn(r)


def code_block(text):
    p = doc.add_paragraph()
    p.paragraph_format.left_indent = Inches(0.25)
    p.paragraph_format.line_spacing = 1.1
    r = p.add_run(text)
    r.font.name = "Consolas"; r.font.size = Pt(9.5); r.font.color.rgb = RGBColor(0x33, 0x33, 0x33)
    return p


def figure(name, width=6.2, caption=""):
    path = FIG / name
    if path.exists():
        doc.add_picture(str(path), width=Inches(width))
        doc.paragraphs[-1].alignment = WD_ALIGN_PARAGRAPH.CENTER
        if caption:
            para(caption, size=9, align=WD_ALIGN_PARAGRAPH.CENTER, color=GREY)


def table(headers, rows):
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Light Grid Accent 1"
    for i, hd in enumerate(headers):
        c = t.rows[0].cells[i]; c.text = ""
        r = c.paragraphs[0].add_run(hd); r.bold = True; r.font.size = Pt(10); _cn(r)
    for row in rows:
        cells = t.add_row().cells
        for i, v in enumerate(row):
            cells[i].text = ""
            r = cells[i].paragraphs[0].add_run(str(v)); r.font.size = Pt(9.5); _cn(r)
    doc.add_paragraph()
    return t


