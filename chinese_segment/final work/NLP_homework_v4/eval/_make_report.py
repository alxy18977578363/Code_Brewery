h("4.5 综述生成与幻觉控制模块", 2)
para("本模块是“性能要求②（无明显幻觉）”的落脚点，也是创新最集中的地方。")
para("（1）受约束的生成：把每条结构化记录编号为 [1][2]…放进提示词，硬性要求模型“所有事实陈述都必须用 [n] 引用、"
     "n 只能取自给定编号、不得编造，也不得引入未出现的方法或数据集名”。综述按固定五段式组织："
     "研究背景 → 主要方法分类 → 各类方法对比 → 研究空白 → 未来方向。")
