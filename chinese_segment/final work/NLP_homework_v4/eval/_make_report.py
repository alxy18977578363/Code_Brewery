h("2.6 TF-IDF 与文本聚类（KMeans）", 2)
para(
    "为了把检索到的论文自动归类成几个“研究方向”，需要先把文字变成计算机能计算的“数字向量”，再做聚类。"
)
term("TF-IDF", "一种衡量“一个词对一篇文档有多重要”的经典方法。它由两部分相乘：TF（词频）指这个词在本篇文档里"
     "出现得多不多；IDF（逆文档频率）指这个词是不是“稀有词”——如果一个词在所有文档里都出现（如“方法”“模型”），"
     "说明它没有区分度，权重就低；如果只在少数文档里出现（如“扩散”“图神经网络”），说明它有区分度，权重就高。"
     "TF-IDF 让每篇论文变成一串数字，相似的论文数字也相近。")
term("KMeans 聚类", "一种把样本自动分成 K 组的算法：它让组内的样本尽量相似、组间尽量不同。本项目用它把论文"
     "按内容自动分成 2–5 个研究方向，每组再用高权重的词作为该方向的标签。")

